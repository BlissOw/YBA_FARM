local function getAllLootItems()
    local items = {}
    local seen = {}
    local function addChildren(parent)
        if not parent then return end
        for _, child in ipairs(parent:GetChildren()) do
            if not seen[child] then
                seen[child] = true
                table.insert(items, child)
            end
        end
    end
    local spawns = workspace:FindFirstChild(_BLISS_STR[278])
    if spawns then
        addChildren(spawns:FindFirstChild(_BLISS_STR[279]))
        addChildren(spawns:FindFirstChild(_BLISS_STR[280]))
        addChildren(spawns:FindFirstChild(_BLISS_STR[281]))
        addChildren(spawns:FindFirstChild(_BLISS_STR[282]))
        for _, obj in ipairs(spawns:GetChildren()) do
            if obj.Name ~= _BLISS_STR[279] and (obj:IsA(_BLISS_STR[162]) or obj:IsA(_BLISS_STR[260])) then
                if not seen[obj] then
                    seen[obj] = true
                    table.insert(items, obj)
                end
            end
        end
    end
    addChildren(workspace:FindFirstChild(_BLISS_STR[280]))
    addChildren(workspace:FindFirstChild(_BLISS_STR[282]))
    addChildren(workspace:FindFirstChild(_BLISS_STR[283]))
    addChildren(workspace:FindFirstChild(_BLISS_STR[279]))
    return items
end
local function findNearestLoot()
    local allItems = getAllLootItems()
    local bestItem, bestName, bestScore, totalCount = nil, nil, -math.huge, 0
    for _, item in ipairs(allItems) do
        local name = getItemDisplayName(item)
        if (SellableItems[name] or KeepItems[name])
            and isItemAvailable(item)
            and not isItemFull(name)
            and not isItemBlacklisted(item) then
            totalCount = totalCount + 1
            local pos = getItemPosition(item)
            if pos and State.RootPart then
                local dist = (pos - State.RootPart.Position).Magnitude
                local price = ItemPrices[name] or 100
                local score
                if KeepItems[name] then
                    score = 10000000 - dist
                else
                    score = (price * 2.5) - dist
                end
                if score > bestScore then
                    bestScore = score
                    bestItem = item
                    bestName = name
                end
            end
        end
    end
    return bestItem, bestName, totalCount
end
local function grabItem(item, name)
    local pos = getItemPosition(item)
    if not pos then return false end
    local prox = item:FindFirstChildWhichIsA(_BLISS_STR[234], true)
    local before = countItem(name)
    lockToPosition(pos)
    task.wait(0.15 + math.random() * 0.08)
    if prox then
        SafePrompt(prox)
    end
    local timeout = Config.GrabTimeout + math.random() * 0.3
    local started = tick()
    local success = false
    while (tick() - started < timeout) and not CleaningUp do
        if countItem(name) > before then
            success = true
            break
        end
        if not item.Parent or not isItemAvailable(item) then
            break
        end
        task.wait(0.08 + math.random() * 0.07)
    end
    unlockPosition()
    if success and KeepItems[name] then
        State.RaresFound = State.RaresFound + 1
        if name == _BLISS_STR[23] then
            Webhook_SendLuckyArrow(_BLISS_STR[284], countLuckyArrows())
        else
            Webhook_SendRareItem(name, countItem(name))
        end
    end
    return success
end
local function farmStep()
    local item, name, _ = findNearestLoot()
    if item then
        if grabItem(item, name) then
            State.TotalPicked = State.TotalPicked + 1
            State.LastLootTime = tick()
            task.wait(0.12 + math.random() * 0.08)
        else
            State.Blacklist[item] = tick()
        end
    else
        if tick() - State.LastLootTime > Config.DroughtSeconds then
            doServerHop(_BLISS_STR[285])
            task.wait(2.5)
            pcall(refreshCharacter)
            State.LastLootTime = tick()
        else
            teleportTo(PatrolPoints[math.random(1, #PatrolPoints)])
            task.wait(0.4 + math.random() * 0.15)
        end
    end
end
