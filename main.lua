_G.BlissFarm_Cleanup = function()
    CleaningUp = true
    State.Running = false
    for _, conn in ipairs(Connections) do
        pcall(function() conn:Disconnect() end)
    end
    Connections = {}
    unlockPosition()
    pcall(function()
        if ScreenGui and ScreenGui.Parent then
            ScreenGui:Destroy()
        end
    end)
    _G.BlissFarm_Cleanup = nil
end
