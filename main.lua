                pcall(refreshCharacter)
            end
        end)
        if ok and err == _BLISS_STR[295] then
            break
        elseif not ok then
            warn(_BLISS_STR[310] .. tostring(err))
            task.wait(0.5)
        end
        task.wait(0.15 + math.random() * 0.05)
    end
end)
