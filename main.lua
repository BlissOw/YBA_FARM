local function sendDiscordWebhook(embedData, content)
    if not Config.WebhookEnabled or not Config.WebhookUrl or Config.WebhookUrl == "" then
        return false
    end
    local reqFunc = (type(request) == _BLISS_STR[1] and request)
        or (type(http_request) == _BLISS_STR[1] and http_request)
        or (syn and type(syn.request) == _BLISS_STR[1] and syn.request)
        or (http and type(http.request) == _BLISS_STR[1] and http.request)
    if not reqFunc then
        return false
    end
    local payload = {
        username = _BLISS_STR[55],
        avatar_url = _BLISS_STR[56],
        content = content or "",
        embeds = { embedData }
    }
    local success, jsonPayload = pcall(function()
        return HttpService:JSONEncode(payload)
    end)
    if not success or not jsonPayload then return false end
    task.spawn(function()
        pcall(function()
            reqFunc({
                Url = Config.WebhookUrl,
                Method = _BLISS_STR[57],
                Headers = {
                    [_BLISS_STR[58]] = _BLISS_STR[59]
                },
                Body = jsonPayload
            })
        end)
    end)
    return true
end
