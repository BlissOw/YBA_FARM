local function doServerHop(reason, force)
    if not force and not Config.ServerHopEnabled then
        updateStatus(_BLISS_STR[174] .. tostring(reason))
        return
    end
    updateStatus(_BLISS_STR[175] .. tostring(reason))
    local qot = queue_on_teleport or (syn and syn.queue_on_teleport) or (fluxus and fluxus.queue_on_teleport)
    if qot then
        pcall(function()
            qot('loadstring(game:HttpGet(_BLISS_STR[176] .. tostring(tick())))()')
        end)
    end
    local validServers = {}
    local placeId = tostring(game.PlaceId)
    local currentJob = tostring(game.JobId)
    pcall(function()
        local url = _BLISS_STR[177] .. placeId .. _BLISS_STR[178]
        local raw = game:HttpGet(url)
        local data = HttpService:JSONDecode(raw)
        if data and data.data then
            for _, sv in ipairs(data.data) do
                if type(sv) == _BLISS_STR[12] and sv.id and sv.id ~= currentJob and sv.playing and sv.maxPlayers then
                    if sv.playing >= 2 and sv.playing < (sv.maxPlayers - 1) then
                        table.insert(validServers, sv.id)
                    end
                end
            end
        end
    end)
    if #validServers == 0 then
        pcall(function()
            local url = _BLISS_STR[177] .. placeId .. _BLISS_STR[179]
            local raw = game:HttpGet(url)
            local data = HttpService:JSONDecode(raw)
            if data and data.data then
                for _, sv in ipairs(data.data) do
                    if type(sv) == _BLISS_STR[12] and sv.id and sv.id ~= currentJob and sv.playing and sv.maxPlayers then
                        if sv.playing < sv.maxPlayers then
                            table.insert(validServers, sv.id)
                        end
                    end
                end
            end
        end)
    end
    if #validServers > 0 then
        local chosenId = validServers[math.random(1, #validServers)]
        updateStatus(_BLISS_STR[180] .. tostring(chosenId):sub(1, 8) .. _BLISS_STR[181])
        task.wait(0.3)
        local tpOk, tpErr = pcall(function()
            TeleportService:TeleportToPlaceInstance(game.PlaceId, chosenId, LocalPlayer)
        end)
        if not tpOk then
            warn(_BLISS_STR[182] .. tostring(tpErr))
            pcall(function()
                TeleportService:Teleport(game.PlaceId, LocalPlayer)
            end)
        end
    else
        updateStatus(_BLISS_STR[183])
        task.wait(0.3)
        pcall(function()
            TeleportService:Teleport(game.PlaceId, LocalPlayer)
        end)
    end
end
