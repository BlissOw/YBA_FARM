local SafeClickButton = function(btn)
    if not btn or not btn.Parent then return false end
    local clicked = false
    if type(firesignal) == _BLISS_STR[1] then
        for _, ev in ipairs({_BLISS_STR[37], _BLISS_STR[38], _BLISS_STR[39], _BLISS_STR[40], _BLISS_STR[41]}) do
            pcall(function()
                if btn[ev] then
                    firesignal(btn[ev])
                    clicked = true
                end
            end)
        end
    end
    if type(getconnections) == _BLISS_STR[1] then
        pcall(function()
            for _, sigName in ipairs({_BLISS_STR[37], _BLISS_STR[39], _BLISS_STR[38]}) do
                local sig = btn[sigName]
                if sig then
                    for _, cn in ipairs(getconnections(sig)) do
                        pcall(function() cn.Function() end)
                        pcall(function() if cn.Fire then cn:Fire() end end)
                        clicked = true
                    end
                end
            end
        end)
    end
    if not clicked and VirtualUser then
        pcall(function()
            local x = math.floor(btn.AbsolutePosition.X + btn.AbsoluteSize.X / 2)
            local y = math.floor(btn.AbsolutePosition.Y + btn.AbsoluteSize.Y / 2)
            VirtualUser:ClickButton1(Vector2.new(x, y))
            clicked = true
        end)
    end
    if not clicked and VirtualInputManager then
        pcall(function()
            local x = btn.AbsolutePosition.X + btn.AbsoluteSize.X / 2
            local y = btn.AbsolutePosition.Y + btn.AbsoluteSize.Y / 2
            VirtualInputManager:SendMouseButtonEvent(x, y, 0, true, game, 1)
            VirtualInputManager:SendMouseButtonEvent(x, y, 0, false, game, 1)
            clicked = true
        end)
    end
    return clicked
end
