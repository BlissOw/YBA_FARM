                if isArrowsGoalReached and isMoneyGoalReached and isAllStacksFull then
                    updateStatus(
                        _BLISS_STR[299],
                        string.format(_BLISS_STR[300], arrows, completedStacks, totalStacks),
                        _BLISS_STR[301]
                    )
                    Webhook_SendMilestone(
                        _BLISS_STR[299],
                        string.format(_BLISS_STR[302], LocalPlayer.Name, arrows, completedStacks, totalStacks),
                        10181046,
                        true
                    )
                    return _BLISS_STR[303]
                elseif not isArrowsGoalReached then
                    StatusLine1.Text = string.format(_BLISS_STR[304], arrows, Config.TargetArrows)
                    StatusLine2.Text = string.format(_BLISS_STR[305], money, candyCount, sellCount)
                    local canBuy = (tick() - (State.LastBuyTime or 0) > 4) and (tick() - (State.LastBuyFailTime or 0) > 8)
                    if Config.HalloweenEnabled and candyCount >= Config.CandyTurnInThreshold then
                        turnInCandyToJack()
                        task.wait(1.5 + math.random() * 0.4)
                        buyHalloweenLuckyArrow()
                        task.wait(1.8 + math.random() * 0.4)
                    elseif money >= Config.ArrowPrice and canBuy then
                        buyLuckyArrow()
                        task.wait(2.0 + math.random() * 0.5)
                    elseif sellCount >= Config.SellThreshold then
                        updateStatus(_BLISS_STR[306] .. sellCount .. _BLISS_STR[307])
                        trySell()
                        task.wait(1.8 + math.random() * 0.5)
                    else
                        farmStep()
                    end
                elseif not isMoneyGoalReached then
                    if State.LastPhase < 2 then
                        State.LastPhase = 2
                        Webhook_SendMilestone(
                            _BLISS_STR[308] .. arrows .. _BLISS_STR[309],
                            string.format(_BLISS_STR[310], arrows),
                            16766720,
                            false
                        )
                    end
                    StatusLine1.Text = string.format(_BLISS_STR[311], money)
                    StatusLine2.Text = string.format(_BLISS_STR[312], arrows, countCandy(), sellCount, Config.SellThreshold)
                    if sellCount >= Config.SellThreshold then
                        updateStatus(_BLISS_STR[306] .. sellCount .. _BLISS_STR[313])
                        trySell()
                        task.wait(1.8 + math.random() * 0.5)
                    else
                        farmStep()
                    end
                else
                    if State.LastPhase < 3 then
                        State.LastPhase = 3
                        Webhook_SendMilestone(
                            _BLISS_STR[314],
                            _BLISS_STR[315],
                            65280,
                            false
                        )
                    end
                    StatusLine1.Text = string.format(_BLISS_STR[316], completedStacks, totalStacks)
                    StatusLine2.Text = string.format(_BLISS_STR[317], arrows)
                    farmStep()
                end
                StatusLine3.Text = string.format(_BLISS_STR[318],
                    uptimeMinutes, sessionProfit, State.RaresFound)
            else
                task.wait(0.5)
                pcall(refreshCharacter)
            end
        end)
        if ok and err == _BLISS_STR[303] then
            break
        elseif not ok then
            warn(_BLISS_STR[319] .. tostring(err))
            task.wait(0.5)
        end
        task.wait(0.15 + math.random() * 0.05)
    end
end)
