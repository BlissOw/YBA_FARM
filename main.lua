        if data and data.data then
            for _, sv in ipairs(data.data) do
                if type(sv) == _BLISS_STR[12] and sv.id and sv.id ~= currentJob and sv.playing and sv.maxPlayers then
                    if sv.playing >= 2 and sv.playing < (sv.maxPlayers - 1) then
                        table.insert(validServers, sv.id)
                    end
                end
            end
        end
    end)
    if #validServers == 0 then
        pcall(function()
            local url = _BLISS_STR[178] .. placeId .. _BLISS_STR[180]
            local raw = game:HttpGet(url)
            local data = HttpService:JSONDecode(raw)
            if data and data.data then
                for _, sv in ipairs(data.data) do
                    if type(sv) == _BLISS_STR[12] and sv.id and sv.id ~= currentJob and sv.playing and sv.maxPlayers then
                        if sv.playing < sv.maxPlayers then
                            table.insert(validServers, sv.id)
                        end
                    end
                end
            end
        end)
    end
    if #validServers > 0 then
        local chosenId = validServers[math.random(1, #validServers)]
        updateStatus(_BLISS_STR[181] .. tostring(chosenId):sub(1, 8) .. _BLISS_STR[182])
        task.wait(0.3)
        local tpOk, tpErr = pcall(function()
            TeleportService:TeleportToPlaceInstance(game.PlaceId, chosenId, LocalPlayer)
