                        updateStatus(_BLISS_STR[304] .. sellCount .. _BLISS_STR[305])
                        trySell()
                        task.wait(1.8 + math.random() * 0.5)
                    else
                        farmStep()
                    end
                elseif not isMoneyGoalReached then
                    if State.LastPhase < 2 then
                        State.LastPhase = 2
                        Webhook_SendMilestone(
                            _BLISS_STR[306] .. arrows .. _BLISS_STR[307],
                            string.format(_BLISS_STR[308], arrows),
                            16766720,
                            false
                        )
                    end
                    StatusLine1.Text = string.format(_BLISS_STR[309], money)
                    StatusLine2.Text = string.format(_BLISS_STR[310], arrows, countCandy(), sellCount, Config.SellThreshold)
                    if sellCount >= Config.SellThreshold then
                        updateStatus(_BLISS_STR[304] .. sellCount .. _BLISS_STR[311])
                        trySell()
                        task.wait(1.8 + math.random() * 0.5)
                    else
                        farmStep()
                    end
                else
                    if State.LastPhase < 3 then
                        State.LastPhase = 3
                        Webhook_SendMilestone(
                            _BLISS_STR[312],
                            _BLISS_STR[313],
                            65280,
                            false
                        )
                    end
                    StatusLine1.Text = string.format(_BLISS_STR[314], completedStacks, totalStacks)
                    StatusLine2.Text = string.format(_BLISS_STR[315], arrows)
                    farmStep()
                end
                StatusLine3.Text = string.format(_BLISS_STR[316],
                    uptimeMinutes, sessionProfit, State.RaresFound)
            else
                task.wait(0.5)
                pcall(refreshCharacter)
            end
        end)
        if ok and err == _BLISS_STR[301] then
            break
        elseif not ok then
            warn(_BLISS_STR[317] .. tostring(err))
            task.wait(0.5)
        end
        task.wait(0.15 + math.random() * 0.05)
    end
end)
