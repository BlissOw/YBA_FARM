                table.insert(items, child)
            end
        end
    end
    local spawns = workspace:FindFirstChild(_BLISS_STR[267])
    if spawns then
        addChildren(spawns:FindFirstChild(_BLISS_STR[268]))
        addChildren(spawns:FindFirstChild(_BLISS_STR[269]))
